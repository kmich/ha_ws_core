def _window_lang(language: str | None) -> str:
    code = language.split("-")[0].lower() if isinstance(language, str) and language else "en"
    return code if code in _WINDOW_TEXT else "en"


def window_text(language: str | None, key: str, **fmt: object) -> str:
    """Return a localized weather-window explanation string."""
    table = _WINDOW_TEXT[_window_lang(language)]
    return table.get(key, _WINDOW_TEXT["en"][key]).format(**fmt)


def window_field_labels(language: str | None, fields: list[str] | tuple[str, ...]) -> str:
    """Return a comma-separated localized list of profile limit names."""
    table = _WINDOW_FIELD_LABELS[_window_lang(language)]
    return ", ".join(table.get(f, _WINDOW_FIELD_LABELS["en"].get(f, f)) for f in fields)
